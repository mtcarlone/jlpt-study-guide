#!/usr/bin/env python3
"""Download the j-nihongo.com N5 and N4 vocabulary lists and write every word into the
"## Vocabulary" section of _quiz_bank.md (replacing that section). Words, readings and
meanings are copied exactly as the site gives them.

Usage: python3 scripts/import_vocabulary.py   (then run scripts/build_quiz.py)
"""
import html
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BANK = ROOT / "_quiz_bank.md"
URLS = {"N5": "https://j-nihongo.com/vocabulary/jlpt/n5/", "N4": "https://j-nihongo.com/vocabulary/jlpt/n4/"}
HEADER = """## Vocabulary

From the j-nihongo.com JLPT vocabulary lists ({urls}), copied as given. Generated by scripts/import_vocabulary.py; edits here are overwritten when it is re-run.

| ID | Level | Word | Reading | Meaning |
| --- | --- | --- | --- | --- |
"""
SECTION = re.compile(r"^## Vocabulary\n.*?(?=^## |\Z)", re.S | re.M)


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (jlpt-study-tool)"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode("utf-8")


def field(row, pattern):
    m = re.search(pattern, row, re.S)
    text = html.unescape(re.sub(r"<[^>]+>", "", m.group(1))).strip() if m else ""
    return text.replace("|", "/")


def words(page):
    for row in re.findall(r'<article class="word-row".*?</article>', page, re.S):
        yield (field(row, r"<h2[^>]*>(.*?)</h2>"),
               field(row, r'class="word-reading"[^>]*>(.*?)</p>'),
               field(row, r'class="word-english"[^>]*>(.*?)</p>'))


def main():
    lines = []
    for level, url in URLS.items():
        found = list(words(fetch(url)))
        if not found:
            raise SystemExit(f"No words found at {url}; the page layout may have changed.")
        for n, (term, reading, meaning) in enumerate(found, 1):
            lines.append(f"| VOCAB-{level}-{n:03d} | {level} | {term} | {reading} | {meaning} |")
        print(f"{level}: {len(found)} words")

    section = HEADER.format(urls=", ".join(URLS.values())) + "\n".join(lines) + "\n"
    text = BANK.read_text(encoding="utf-8")
    if SECTION.search(text):
        text = SECTION.sub(lambda _: section + "\n", text, count=1).rstrip("\n") + "\n"
    else:
        text = text.rstrip("\n") + "\n\n" + section
    BANK.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
